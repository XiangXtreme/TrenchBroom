struct Token
{
  qsizetype start;
  qsizetype length;
  QString text;
};

bool matchesFlag(const QString& token, const QString& flag)
{
  return canonicalHltoolsFlag(token) == flag;
}

// Preserve every untouched byte, including quoted paths and EL expressions with
// spaces. Only literal option tokens are editable through the visual controls.
std::vector<Token> tokens(const QString& text)
{
  auto result = std::vector<Token>{};
  for (qsizetype i = 0; i < text.size();)
  {
    if (text[i].isSpace())
    {
      ++i;
      continue;
    }
    const auto start = i;
    auto quote = QChar{};
    auto depth = 0;
    auto escaped = false;
    while (i < text.size())
    {
      const auto c = text[i];
      if (!escaped)
      {
        if (!quote.isNull())
        {
          if (c == quote)
            quote = {};
        }
        else if (c == '"' || (depth > 0 && c == '\''))
          quote = c;
        else if (c == '{' && (depth > 0 || (i > start && text[i - 1] == '$')))
          ++depth;
        else if (c == '}' && depth > 0)
          --depth;
        else if (c.isSpace() && depth == 0)
          break;
      }
      escaped = c == '\\' && !escaped;
      ++i;
    }
    auto value = text.mid(start, i - start);
    if (
      value.size() >= 2 && value.startsWith('"') && value.endsWith('"')
      && !value.contains("${"))
      value = value.mid(1, value.size() - 2);
    result.push_back({start, i - start, std::move(value)});
  }
  return result;
}

// Skip registered value tokens: a path named "-noskyclip" is not a sky option.
std::vector<size_t> occurrences(const std::vector<Token>& arguments, const QString& flag)
{
  auto result = std::vector<size_t>{};
  for (size_t i = 0; i < arguments.size(); ++i)
  {
    if (matchesFlag(arguments[i].text, flag))
      result.push_back(i);
    if (const auto* option = findHltoolsCompilerOption(arguments[i].text))
      i += std::min(size_t(option->arity), arguments.size() - i - 1);
  }
  return result;
}

QString quotedValue(QString value)
{
  // Keep expressions editable and quote paths as one command argument.
  if (value.startsWith('"') && value.endsWith('"'))
    return value;
  if (value.contains(' ') || value.contains('\t'))
    return '"' + value + '"';
  return value;
}
